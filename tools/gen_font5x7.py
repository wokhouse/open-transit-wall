#!/usr/bin/env python3
"""Regenerate firmware/src/font5x7.h from Adafruit GFX's glcdfont.c.

The vendored 5x7 font lets on-panel text (splash/error screens) go through
Screen::drawPixel — the tile-mapped path — instead of the DMA library's
direct drawPixel, which ignores our chain layout.

    python3 tools/gen_font5x7.py            # fetch from GitHub master
    python3 tools/gen_font5x7.py glcdfont.c  # from a local copy
"""
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "firmware" / "src" / "font5x7.h"
SRC_URL = "https://raw.githubusercontent.com/adafruit/Adafruit-GFX-Library/master/glcdfont.c"

HEADER = '''#pragma once
// Auto-generated by tools/gen_font5x7.py — do not edit.
// The classic Adafruit GFX 5x7 font (glcdfont.c, chars 32-126), vendored so
// on-panel text goes through Screen::drawPixel (tile-mapped) instead of the
// library's direct DMA path. Column-major: 5 bytes per glyph, each byte is a
// column, bit 0 = top row. Source: Adafruit GFX (MIT).

#ifdef ARDUINO
#include <pgmspace.h>
#else
#define PROGMEM
#endif
#include <stdint.h>

#define FONT5X7_FIRST 32
#define FONT5X7_LAST 126

static const uint8_t font5x7[] PROGMEM = {
'''

FOOTER = '''
};
'''


def main() -> int:
    if len(sys.argv) > 1:
        src = Path(sys.argv[1]).read_text()
    else:
        try:
            with urllib.request.urlopen(SRC_URL, timeout=30) as r:
                src = r.read().decode()
        except OSError:
            # Some macOS Pythons ship without a CA bundle; curl has its own.
            src = subprocess.run(
                ["curl", "-fsSL", SRC_URL], capture_output=True, text=True,
                check=True, timeout=30,
            ).stdout
    body = src.split("static const unsigned char font[] PROGMEM = {")[1]
    body = body.split("};")[0]
    vals = re.findall(r"0x[0-9A-Fa-f]{2}", body)
    if len(vals) == 95 * 5:
        glyphs = vals  # old table: exactly chars 32-126
    elif len(vals) == 256 * 5:
        glyphs = vals[32 * 5 : 127 * 5]  # modern table: chars 0-255
    else:
        print(f"unexpected font table: {len(vals)} bytes", file=sys.stderr)
        return 1
    lines = []
    for c in range(95):
        row = ", ".join(glyphs[c * 5 : (c + 1) * 5])
        glyph = chr(32 + c)
        comment = "space" if c == 0 else glyph
        # A backslash at the end of a // comment is a line continuation: the
        # preprocessor would splice (and comment out) the NEXT glyph's bytes,
        # silently shifting every later glyph by one. Never emit a bare \.
        if comment == "\\":
            comment = "backslash"
        lines.append(f"  {row},  // {comment}")
    OUT.write_text(HEADER + "\n".join(lines) + FOOTER)
    print(f"wrote {OUT} ({len(vals)} bytes, chars 32-126)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
