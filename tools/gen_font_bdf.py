#!/usr/bin/env python3
"""Generate a column-major 5x7-style C font header from a BDF bitmap font.

Usage: python3 tools/gen_font_bdf.py <font.bdf> <out.h> --name font_tomthumb
       [--first 32 --last 126]

The BDF is parsed for glyphs in [--first, --last]; each glyph is normalized
into a fixed cell (cell width/height from --cell, default 4x6) and emitted
column-major with bit 0 = top row, matching firmware/src/font5x7.h so
status_screen.cpp can render either font unchanged.
"""
import argparse
import re
import sys


def parse_bdf(path):
    """Return {codepoint: (bbx, rows_of_hex_bytes)} from a BDF file."""
    glyphs = {}
    text = open(path, encoding="utf-8", errors="replace").read()
    for chunk in text.split("STARTCHAR")[1:]:
        m_enc = re.search(r"ENCODING\s+(-?\d+)", chunk)
        m_bbx = re.search(r"BBX\s+(\d+)\s+(\d+)\s+(-?\d+)\s+(-?\d+)", chunk)
        m_bm = re.search(r"BITMAP\n((?:[0-9A-Fa-f]+\n)+)ENDCHAR", chunk)
        if not (m_enc and m_bbx and m_bm):
            continue
        cp = int(m_enc.group(1))
        if cp < 0:
            continue
        w, h, xoff, yoff = (int(g) for g in m_bbx.groups())
        hexbytes = m_bm.group(1).split()
        # BDF rows are top-to-bottom, MSB-first, padded to byte multiples.
        rows = []
        for hb in hexbytes:
            v = int(hb, 16)
            bits = len(hb) * 4
            rows.append([(v >> (bits - 1 - i)) & 1 for i in range(bits)])
        glyphs[cp] = ((w, h, xoff, yoff), rows)
    return glyphs


def normalize(glyph, cell_w, cell_h, ascent):
    """Rasterize one glyph into a cell_w x cell_h grid of rows (top first)."""
    (w, h, xoff, yoff), rows = glyph
    grid = [[0] * cell_w for _ in range(cell_h)]
    for ry, row in enumerate(rows):
        # BDF y: row 0 is the TOP of the BBX; the BBX top sits at
        # baseline + yoff + h - 1 in font coords. Convert to cell row:
        # cell row 0 = ascent line above baseline... use direct mapping:
        # font_y_of_row = yoff + h - 1 - ry  (font coords, up=positive)
        # cell_row = (ascent - 1) - font_y  ... baseline at cell row ascent.
        font_y = yoff + h - 1 - ry
        cell_row = (ascent - 1) - font_y
        if cell_row < 0 or cell_row >= cell_h:
            continue
        for rx in range(w):
            if rx < len(row) and row[rx]:
                cell_col = xoff + rx
                if 0 <= cell_col < cell_w:
                    grid[cell_row][cell_col] = 1
    return grid


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("bdf")
    ap.add_argument("out")
    ap.add_argument("--name", required=True, help="C array name")
    ap.add_argument("--first", type=int, default=32)
    ap.add_argument("--last", type=int, default=126)
    ap.add_argument("--cell", default="4x6", help="cell WxH")
    ap.add_argument("--ascent", type=int, help="rows above baseline (from BDF if omitted)")
    args = ap.parse_args()

    cell_w, cell_h = (int(v) for v in args.cell.lower().split("x"))
    glyphs = parse_bdf(args.bdf)

    # FONT_ASCENT from the BDF header if present.
    ascent = args.ascent
    if ascent is None:
        m = re.search(r"FONT_ASCENT\s+(\d+)", open(args.bdf).read())
        if not m:
            sys.exit("no FONT_ASCENT in BDF; pass --ascent")
        ascent = int(m.group(1))

    missing = [cp for cp in range(args.first, args.last + 1) if cp not in glyphs]
    if missing:
        sys.exit(f"BDF missing codepoints: {missing}")

    cols = []
    for cp in range(args.first, args.last + 1):
        grid = normalize(glyphs[cp], cell_w, cell_h, ascent)
        for c in range(cell_w):
            byte = 0
            for r in range(cell_h):
                if grid[r][c]:
                    byte |= 1 << r
            cols.append(byte)

    name = args.name
    with open(args.out, "w") as f:
        f.write(
            "#pragma once\n"
            f"// Auto-generated by tools/gen_font_bdf.py from {args.bdf} — do not edit.\n"
            f"// {cell_w}x{cell_h} cell, ascent {ascent}, column-major: {cell_w} bytes per\n"
            f"// glyph, each byte is a column, bit 0 = top row. Same layout as font5x7.h.\n"
            "\n"
            "#ifdef ARDUINO\n"
            "#include <pgmspace.h>\n"
            "#else\n"
            "#define PROGMEM\n"
            "#endif\n"
            "#include <stdint.h>\n"
            "\n"
            f"#define {name.upper()}_W {cell_w}\n"
            f"#define {name.upper()}_H {cell_h}\n"
            f"#define {name.upper()}_ASCENT {ascent}\n"
            f"#define {name.upper()}_FIRST {args.first}\n"
            f"#define {name.upper()}_LAST {args.last}\n"
            "\n"
            f"static const uint8_t {name}[] PROGMEM = {{\n"
        )
        for i in range(0, len(cols), 12):
            f.write("  " + " ".join(f"0x{b:02x}," for b in cols[i:i+12]) + "\n")
        f.write("};\n")
    print(f"wrote {args.out}: {len(cols)//cell_w} glyphs, {cell_w}x{cell_h}, ascent {ascent}")


if __name__ == "__main__":
    main()
