#!/usr/bin/env python3
"""Generate the firmware backdrop (water/land bitmap) for any matrix size.

Rasterizes the coarse shoreline polygons in server/geo.py at the requested
pixel size using the exact same projection as firmware/src/map_project.h,
packs it RLE, and writes firmware/src/backdrop.h as a table keyed by agency
id. Regenerate after changing PANEL_CHAIN_W/H, or to add an agency:

    python3 tools/gen_backdrop.py --agency sf --w 64 --h 64
    python3 tools/gen_backdrop.py --agency sf --agency ct --w 64 --h 64

Each entry carries the bounding box it was rasterized for (from
server/agencies.json), so the firmware can tell when a wall is provisioned
for an agency whose compiled backdrop does not match its map.
"""

import argparse
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "server"))

from geo import LAND_POLYGONS, LAND_RGB, WATER_RGB

AGENCIES_JSON = ROOT / "server" / "agencies.json"

HEADER = """#pragma once
// Auto-generated by tools/gen_backdrop.py --agency {ids} --w {w} --h {h}
// — do not edit. One entry per agency, selected at boot by the provisioned
// agency id (firmware/src/main.cpp). RLE water/land bitmap, row-major:
// (count, colorIndex) byte pairs, 0 = land(2,2,2), 1 = water(0,0,0) —
// colors applied at render time in screen.h.
// Total pixels per entry = BACKDROP_W * BACKDROP_H.

#define BACKDROP_W {w}
#define BACKDROP_H {h}

#ifdef ARDUINO
#include <pgmspace.h>
#else
#define PROGMEM
#endif
#include <stdint.h>

struct BackdropDef {{
  const char *agency;
  double bbox[4];  // lat_min, lat_max, lon_min, lon_max it was rasterized for
  unsigned int rle_len;
  const uint8_t *rle;
}};

{arrays}
static const BackdropDef backdrops[] = {{
{entries}
}};
static const unsigned int backdrop_count =
    sizeof(backdrops) / sizeof(backdrops[0]);
"""


def load_registry():
    return json.loads(AGENCIES_JSON.read_text())


def bbox_of(registry, agency):
    box = registry[agency]["bbox"]
    return (box["lat_min"], box["lat_max"], box["lon_min"], box["lon_max"])


def project_setup(bbox, width: int, height: int, stretch: bool = False):
    """Mirror MapProjection in firmware/src/map_project.h.

    stretch=False (default, matching MAP_STRETCH_TO_FILL 0) is the
    aspect-preserving centered fit; stretch=True maps the bbox onto the full
    display.
    """
    lat_min, lat_max, lon_min, lon_max = bbox
    lat_span = lat_max - lat_min
    lon_span = lon_max - lon_min
    if stretch:
        return {"sx": width / lon_span, "sy": height / lat_span}
    mid_cos = math.cos((lat_min + lat_max) / 2 * math.pi / 180)
    lon_span_cos = lon_span * mid_cos
    scale = min(width / lon_span_cos, height / lat_span)
    return {
        "mid_cos": mid_cos, "scale": scale,
        "off_x": (width - lon_span_cos * scale) / 2,
        "off_y": (height - lat_span * scale) / 2,
    }


def pixel_to_latlon(bbox, width, height, px, py, stretch=False):
    setup = project_setup(bbox, width, height, stretch)
    _, lat_max, lon_min, _ = bbox
    if stretch:
        lon = lon_min + (px + 0.5) / setup["sx"]
        lat = lat_max - (py + 0.5) / setup["sy"]
    else:
        lon = lon_min + (px + 0.5 - setup["off_x"]) / (setup["mid_cos"] * setup["scale"])
        lat = lat_max - (py + 0.5 - setup["off_y"]) / setup["scale"]
    return lat, lon


def point_in_land(polygon, lat, lon):
    """Ray-casting test against the coarse shoreline polygon."""
    inside = False
    n = len(polygon)
    j = n - 1
    for i in range(n):
        lat_i, lon_i = polygon[i]
        lat_j, lon_j = polygon[j]
        if (lon_i > lon) != (lon_j > lon):
            slope = (lat_j - lat_i) / (lon_j - lon_i)
            if lat < lat_i + slope * (lon - lon_i):
                inside = not inside
        j = i
    return inside


def _as_polygons(polygon):
    """Normalize any geo.py LAND_POLYGONS shape to a list of polygons, each a
    list of rings (outer first, then holes). Accepts a bare ring (sf), a list
    of rings, or a list of ring-lists (NYC)."""
    if isinstance(polygon[0], tuple):
        return [[polygon]]
    if isinstance(polygon[0][0], tuple):
        return [polygon]
    return list(polygon)


def rasterize(bbox, polygon, width, height, stretch=False):
    """Land=0 / water=1 index per pixel. Holes are honored: a pixel is land
    when it falls inside an odd number of rings of any one polygon."""
    if polygon is None:
        return [1] * (width * height)  # no shoreline traced: all water
    polygons = _as_polygons(polygon)
    out = []
    for py in range(height):
        for px in range(width):
            lat, lon = pixel_to_latlon(bbox, width, height, px, py, stretch)
            land = any(
                sum(point_in_land(ring, lat, lon) for ring in rings) % 2 == 1
                for rings in polygons)
            out.append(0 if land else 1)
    return out


def rle_encode(indices):
    runs = []
    current, count = None, 0
    for value in indices:
        if value == current:
            count += 1
        else:
            while count > 255:  # counts are uint8
                runs.append((255, current))
                count -= 255
            if count:
                runs.append((count, current))
            current, count = value, 1
    while count > 255:
        runs.append((255, current))
        count -= 255
    if count:
        runs.append((count, current))
    return runs


def write_ppm(path, width, height, indices):
    palette = {0: LAND_RGB, 1: WATER_RGB}
    with open(path, "wb") as fh:
        fh.write(f"P6 {width} {height} 255\n".encode())
        for index in indices:
            fh.write(bytes(palette[index]))


def emit_array(agency, runs):
    data = ",\n".join(
        ", ".join(f"0x{count:02X},0x{color:02X}" for count, color in runs[i:i + 16])
        for i in range(0, len(runs), 16)
    )
    return f"static const uint8_t rle_{agency}[] PROGMEM = {{\n{data}\n}};\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--agency", action="append", default=None,
                        help="agency id from server/agencies.json (repeatable; "
                             "default: sf)")
    parser.add_argument("--w", type=int, default=64, help="total display width (px)")
    parser.add_argument("--h", type=int, default=64, help="total display height (px)")
    parser.add_argument("--out", type=Path, default=ROOT / "firmware/src/backdrop.h")
    parser.add_argument("--ppm", type=Path, default=None, help="also write a PPM preview")
    parser.add_argument("--stretch", action="store_true",
                        help="stretch the bbox to fill the display instead of the "
                             "default aspect-preserving fit (must match "
                             "MAP_STRETCH_TO_FILL in config.h)")
    args = parser.parse_args()

    registry = load_registry()
    agencies = args.agency or ["sf"]
    unknown = [a for a in agencies if a not in registry]
    if unknown:
        parser.error(f"not in {AGENCIES_JSON.name}: {','.join(unknown)} "
                     f"(registry ids: {','.join(registry)})")

    arrays, entries = [], []
    for agency in agencies:
        bbox = bbox_of(registry, agency)
        polygon = LAND_POLYGONS.get(agency)
        if polygon is None:
            print(f"warning: {agency} has no shoreline polygon in server/geo.py "
                  "— backdrop will be blank (all water)", file=sys.stderr)
        indices = rasterize(bbox, polygon, args.w, args.h, stretch=args.stretch)
        runs = rle_encode(indices)
        arrays.append(emit_array(agency, runs))
        bbox_c = ", ".join(repr(v) for v in bbox)
        entries.append(f'  {{"{agency}", {{{bbox_c}}}, '
                       f"{len(runs) * 2}, rle_{agency}}},")
        print(f"  {agency}: {len(runs)} RLE runs")
        if args.ppm:
            write_ppm(args.ppm, args.w, args.h, indices)
            print(f"  wrote {args.ppm}")

    args.out.write_text(HEADER.format(
        ids=" --agency ".join(agencies), w=args.w, h=args.h,
        arrays="\n".join(arrays), entries="\n".join(entries)))
    print(f"wrote {args.out} ({args.w}x{args.h}, agencies: {','.join(agencies)})")


if __name__ == "__main__":
    main()
