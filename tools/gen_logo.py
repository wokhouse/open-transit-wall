#!/usr/bin/env python3
"""Rasterize the OTW logo SVG into a 64x64 2-bits-per-pixel bitmap header.

The logo (open transit wall logo.svg) is a CTA-mark-style roundel: red outer
ring, white ring, blue disc, white "otw" wordmark. The panel only ever shows
those four states, so the bitmap is palette-indexed: 2 bits per pixel, 4 pixels
per byte, MSB first, row-major. Index 0 = off (draw nothing), 1 = red,
2 = blue, 3 = white — colors live in status_screen.cpp next to the other
screen colors, not in this header.

Renders the SVG at 8x panel size with resvg (anti-aliased), then reduces each
8x8 block to one palette color by majority vote — supersampling is what keeps
the thin wordmark strokes legible; rendering at 1x and snapping produces noise.

Requires:
    uvx --from resvg-py --with pillow python3 tools/gen_logo.py

Source: assets/logo.svg (tracked; its viewBox is centered on the roundel
with built-in margin). Outputs:
  firmware/src/logo_badge.h   — roundel cropped tight (~26x26) for the
                               error half-row; status_screen.cpp places it:
                               2px | badge | gap | 31px QR | 2px
  firmware/src/logo_bounce.h  — small roundel (~20px) cropped tight, for
                               the DVD-style bouncing splash animation; the
                               animation code owns all positioning.
"""
import io
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DEFAULT_SRC = REPO / "assets/logo.svg"
OUT_BOUNCE = REPO / "firmware/src/logo_bounce.h"
OUT_BADGE = REPO / "firmware/src/logo_badge.h"

SS = 8  # supersample factor: render at 8x, reduce to target by majority vote

# The logo's palette (CTA roundel colors). Quantization targets; the firmware
# draws the same values from status_screen.cpp.
PALETTE = [
    None,                # 0: transparent / off — never drawn
    (0xD3, 0x11, 0x45),  # 1: red ring
    (0x00, 0x78, 0xC1),  # 2: blue disc
    (0xFF, 0xFF, 0xFF),  # 3: white ring + wordmark
]


def snap(r, g, b):
    """Nearest palette index for an opaque RGB pixel."""
    best, bi = None, 0
    for i, col in enumerate(PALETTE):
        if col is None:
            continue
        pr, pg, pb = col
        d = (r - pr) ** 2 + (g - pg) ** 2 + (b - pb) ** 2
        if best is None or d < best:
            best, bi = d, i
    return bi


def render(src, size):
    """Rasterize the SVG at SS x size and reduce to size x size palette
    indices (one per panel pixel, majority vote over each SSxSS block)."""
    from resvg_py import svg_to_bytes
    from PIL import Image
    png = svg_to_bytes(svg_path=str(src), width=size * SS, height=size * SS)
    im = Image.open(io.BytesIO(png)).convert("RGBA")

    # Voting on snapped subpixels (not averaged colors) keeps ring boundaries
    # at their true hue; averaging would turn white-ring edges gray.
    idx = []
    for y in range(size):
        for x in range(size):
            votes = [0] * 4
            for dy in range(SS):
                for dx in range(SS):
                    r, g, b, a = im.getpixel((x * SS + dx, y * SS + dy))
                    if a < 128:
                        votes[0] += 1
                        continue
                    if a < 255:  # composite over black before snapping
                        r, g, b = r * a // 255, g * a // 255, b * a // 255
                    votes[snap(r, g, b)] += 1
            idx.append(max(range(4), key=lambda i: votes[i]))
    return idx


def crop_bbox(idx, size):
    """Return (pixels, w, h) cropped tight to the drawn content's bounding
    box. Used for the badge: spacing is fully controlled by the on-panel
    layout code — a tight bitmap means the layout's ROW_GAP is the real
    visible gap, with no hidden padding. Odd sizes are fine here: the badge
    centers against the QR, not the panel."""
    xs = [i % size for i, v in enumerate(idx) if v]
    ys = [i // size for i, v in enumerate(idx) if v]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    w, h = x1 - x0 + 1, y1 - y0 + 1
    out = [idx[(y0 + j) * size + x0 + i] for j in range(h) for i in range(w)]
    return out, w, h


def emit(out, name, idx, w, h):
    # Pack 2 bits/pixel, 4 px/byte, MSB first, row-major. Rows are padded to
    # a byte boundary (stride = ceil(w/4)*4 px) so any width works.
    stride = (w + 3) // 4 * 4
    packed = bytearray()
    for y in range(h):
        for x in range(0, stride, 4):
            byte = 0
            for k in range(4):
                if x + k < w:
                    byte |= idx[y * w + x + k] << (6 - 2 * k)
            packed.append(byte)

    rows = []
    for i in range(0, len(packed), 16):
        rows.append("  " + " ".join(f"0x{b:02X}," for b in packed[i:i + 16]))
    header = (
        "// Generated by tools/gen_logo.py — do not edit.\n"
        f"// OTW roundel logo, {w}x{h}, palette-indexed 2 bits/pixel "
        "(4 px/byte, MSB first, row-major).\n"
        f"// Rows are padded to a byte boundary: stride {stride}px "
        f"({stride // 4} bytes/row).\n"
        "// Index: 0 = off (skip), 1 = red, 2 = blue, 3 = white.\n"
        "#pragma once\n\n"
        "#ifdef ARDUINO\n"
        "#include <pgmspace.h>\n"
        "#else\n"
        "#define PROGMEM\n"
        "#endif\n"
        "#include <stdint.h>\n\n"
        f"#define LOGO_{name.upper()}_W {w}\n"
        f"#define LOGO_{name.upper()}_H {h}\n"
        f"#define LOGO_{name.upper()}_STRIDE {stride}\n\n"
        f"static const uint8_t logo_{name}[] PROGMEM = {{\n"
        + "\n".join(rows) + "\n};\n"
    )
    out.write_text(header)
    counts = [0] * 4
    for v in idx:
        counts[v] += 1
    print(f"{out.name}: {w}x{h} off={counts[0]} red={counts[1]} "
          f"blue={counts[2]} white={counts[3]} ({len(packed)} bytes)")


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SRC
    if not src.exists():
        sys.exit(f"logo SVG not found: {src}")
    # Badge: rendered at 31 so the roundel crops to 29 — same visible size
    # as the QR symbol, which makes it center perfectly against the QR.
    # status_screen.cpp owns its spacing.
    idx, w, h = crop_bbox(render(src, 31), 31)
    emit(OUT_BADGE, "badge", idx, w, h)
    # Bounce: small roundel for the DVD-style splash animation. Rendered at
    # 36 so the tight crop lands ~34px (user: another 30% over the 26px
    # cut), still with room to roam on 64px. The animation owns all
    # positioning, so no centering is baked in (and none can be wrong).
    idx, w, h = crop_bbox(render(src, 36), 36)
    emit(OUT_BOUNCE, "bounce", idx, w, h)


if __name__ == "__main__":
    main()
