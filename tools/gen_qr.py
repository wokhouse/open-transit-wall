#!/usr/bin/env python3
"""Generate firmware/src/qr_flasher.h — the QR the wall shows for the web flasher.

The wall prints this QR on its splash/error screens so an operator with a
phone can open the web flasher and re-provision or reflash the board.

The encoded URL is the GitHub Pages URL itself — no third-party shortener.
At ECC level L the 47-char URL fits a version-3 QR (29x29 modules), the
same size the TinyURL alias produced, so the panel layout is unchanged and
the link carries no ads, no redirect, and no dependency on a shortener
staying alive. (ECC M would need version 4 / 33x33; L is plenty for a
phone camera at arm's length.)

segno is not a project dependency; run this through uvx:

    uvx --with segno python3 tools/gen_qr.py [url]
"""
import sys

try:
    import segno
except ImportError:
    print("segno missing — run: uvx --with segno python3 tools/gen_qr.py",
          file=sys.stderr)
    sys.exit(1)

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "firmware" / "src" / "qr_flasher.h"
DEFAULT_URL = "https://wokhouse.github.io/open-transit-wall/"

HEADER = '''#pragma once
// Auto-generated by tools/gen_qr.py — do not edit.
// QR of the web flasher URL, bit-packed row-major: qr_rows[y][b] bit
// (7 - (x % 8)) = module (x, y), black = 1. ECC level L (the Pages URL
// itself fits version 3 / 29x29 at L; no shortener needed).

#include <stdint.h>

#define QR_FLASHER_URL "{url}"
#define QR_FLASHER_SIZE {size}

static const uint8_t qr_flasher_rows[{size}][{bytes_per_row}] = {{
{rows}
}};
'''


def main() -> int:
    url = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_URL
    qr = segno.make_qr(url, error="L")
    # qr.matrix excludes the quiet zone; symbol_size() would include it.
    size = len(qr.matrix)
    bpr = (size + 7) // 8
    rows = []
    for y in range(size):
        packed = bytearray(bpr)
        for x in range(size):
            if qr.matrix[y][x]:
                packed[x // 8] |= 1 << (7 - (x % 8))
        row = ", ".join(f"0x{b:02x}" for b in packed)
        rows.append(f"  {{ {row} }},")
    OUT.write_text(HEADER.format(url=url, size=size, bytes_per_row=bpr,
                                 rows="\n".join(rows)))
    print(f"wrote {OUT}: {size}x{size} ECC-L for {url}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
